def P(text, bold_lead=None, italic=False):
    p = doc.add_paragraph()
    if bold_lead:
        p.add_run(bold_lead).bold = True
    r = p.add_run(text); r.italic = italic
    return p


def T(rows, widths=None, bold_first=True):
    t = doc.add_table(rows=len(rows), cols=len(rows[0])); t.style = "Light Grid Accent 1"
    for i, row in enumerate(rows):
        for j, v in enumerate(row):
            cell = t.cell(i, j); cell.text = ""
            run = cell.paragraphs[0].add_run(str(v)); run.font.size = Pt(9)
            run.bold = (i == 0 and bold_first)
            cell.paragraphs[0].paragraph_format.space_after = Pt(0)
            if widths: cell.width = Cm(widths[j])
    doc.add_paragraph().paragraph_format.space_after = Pt(0)
    return t


